#!/usr/bin/env python3
"""
Write tests/vectors.json: skim windows produced by the contract's own cut_window.

    python scripts/gen_vectors.py           # write it
    python scripts/gen_vectors.py --check   # exit 1 when the file is not what the contract produces

The window is the first N whitespace separated words of the title followed by
the text. The site cuts the same text in the browser, and
web/scripts/hash-parity.mjs holds its answer to this file.
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))

from harness import load  # noqa: E402
import genvm_double as D  # noqa: E402

OUT = ROOT / "tests" / "vectors.json"
LONG = " ".join("word%d" % i for i in range(1, 301))
CASES = [
    ("plain", "Rewrite the developer docs", "We ask for 40,000 USDC to rewrite the docs in Q1, paid in two halves.", 5),
    ("the whole text fits", "Short", "Only a few words here.", 80),
    ("the cut falls on the last word", "T", "a b c d e", 4),
    ("an empty title", "", "x y z", 2),
    ("runs of spaces and newlines", "A  B", "c \n\n d\t\te   f", 4),
    ("windows line endings", "T", "one\r\ntwo\r\nthree", 3),
    ("no-break and ideographic spaces", "T U", "v　w x", 4),
    ("control whitespace python splits on", "T", "a\x1cb\x1dc\x1ed\x1fe\x85f\x0bg\x0ch", 6),
    ("zero width space is not whitespace", "T", "a​b c", 2),
    ("persian", "بازنویسی مستندات", "از DAO می‌خواهیم ۴۰٬۰۰۰ دلار برای بازنویسی در دو قسط تأمین کند.", 6),
    ("emoji and astral characters", "Launch \U0001f680", "\U0001f525 fire and \U0001d54f math", 4),
    ("a long text cut at 80", "Title", LONG, 80),
    ("a long text cut at 120", "Title", LONG, 120),
    ("a long text cut at 200", "Title", LONG, 200),
]


def build() -> dict:
    mod = load(D.GL())
    return {
        "about": "Skim windows as the contract computes them. See cut_window in contracts/skim.py. Generated by scripts/gen_vectors.py.",
        "cut": "' '.join((title + ' ' + text).split()[:words])",
        "vectors": [
            {"name": n, "title": t, "text": x, "words": w, "window": mod.cut_window(t, x, w), "word_count": mod.word_count(t, x)}
            for n, t, x, w in CASES
        ],
    }


def main() -> int:
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("tests/vectors.json is not what the contract produces. Run: python scripts/gen_vectors.py")
            return 1
        print("tests/vectors.json matches the contract")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote tests/vectors.json ({len(json.loads(text)['vectors'])} vectors)")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    raise SystemExit(main())
